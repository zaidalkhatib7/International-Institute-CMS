/** The AI copy for a language; anything but Arabic reads English. */
export function aiCopy(language) {
  return language === 'ar' ? AI_COPY.ar : AI_COPY.en
}

/** A family's name in the language asked; an unknown family is shown as its code in words. */
export function familyLabel(family, language) {
  const copy = aiCopy(language)
  return copy.families[family] || String(family ?? '').replaceAll('_', ' ')
}
