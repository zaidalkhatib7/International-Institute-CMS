import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import DynamicAssessmentPanel, { COPY, GENERATION_POLL_MS } from './DynamicAssessmentPanel'
import { AI_COPY } from '../../shared/ai/aiCopy'
import { AI_RUN_WAITING_POLL_MS } from '../../shared/ai/aiState'
import { FALLBACK_PROVENANCE, PRIMARY_PROVENANCE, waitingRun } from '../../../test/aiFixtures'

/*
 * THE ENTRY QUIZ WHEN THE AI SERVICE IS BUSY (AI resilience, Release G,
 * AI-RESILIENCE-SPEC §5.2, §7.3, §9.4):
 *
 *   - the draft says which model made it (until now only the audit did), and a
 *     question regenerated by another call names its own model;
 *   - a draft run waiting to retry says when it tries next, reads the set again
 *     every half minute, and Retry now starts it at once through the server's
 *     own route; it holds Generate, but not the set's own controls: continuing
 *     by hand closes the waiting run on the server (fix review of 23 Oct 2026);
 *   - a draft run that stopped because the AI service stayed busy says so;
 *   - the final evaluation runs on the queue: queued and running say so and
 *     hold the button, waiting to retry offers Retry now, and the evaluation
 *     says which model made it.
 */

const mocks = vi.hoisted(() => ({
  fetchDynamicAssessments: vi.fn(),
  fetchDynamicAssessment: vi.fn(),
  createDynamicAssessment: vi.fn(),
  generateDynamicAssessmentDraft: vi.fn(),
  approveAllDynamicAssessmentItems: vi.fn(),
  approveDynamicAssessmentItem: vi.fn(),
  addDynamicAssessmentItem: vi.fn(),
  updateDynamicAssessmentItem: vi.fn(),
  rejectDynamicAssessmentItem: vi.fn(),
  regenerateDynamicAssessmentItem: vi.fn(),
  sendDynamicAssessment: vi.fn(),
  reissueDynamicAssessment: vi.fn(),
  cancelDynamicAssessment: vi.fn(),
  rescoreDynamicAssessment: vi.fn(),
  finalEvaluateDynamicAssessment: vi.fn(),
  exportDynamicAssessment: vi.fn(),
}))

vi.mock('../services/rplService', () => mocks)

const aiApi = vi.hoisted(() => ({ retryAiGenerationNow: vi.fn() }))
vi.mock('../../shared/ai/aiServiceApi', () => aiApi)

const EN = COPY.en

function items(count, status = 'approved', extra = {}) {
  return Array.from({ length: count }, (_, index) => ({
    id: 100 + index,
    status,
    type: 'knowledge',
    is_ai_generated: true,
    prompt: { generated: `Question ${index + 1}` },
    options: [{ id: 'A', text: 'One' }, { id: 'B', text: 'Two' }, { id: 'C', text: 'Three' }],
    ...extra,
  }))
}

function draftSet(overrides = {}) {
  return { id: 7, status: 'pending_review', recommended_question_count: 25, active_items: items(25), generation: null, ...overrides }
}

/** An answered set: every question answered and submitted, ready for the final evaluation. */
function answeredSet(overrides = {}) {
  return {
    id: 7,
    status: 'answered',
    issued_at: '2026-10-20T09:00:00Z',
    answers_submitted_at: '2026-10-21T09:00:00Z',
    time_limit_minutes: 60,
    active_items: items(25, 'approved', { response: { selected_option_id: 'A' } }),
    ...overrides,
  }
}

function renderPanel(sets, language = 'en') {
  mocks.fetchDynamicAssessments.mockResolvedValue({ data: [{ id: 7 }] })
  for (const set of sets) mocks.fetchDynamicAssessment.mockResolvedValueOnce({ data: set })
  mocks.fetchDynamicAssessment.mockResolvedValue({ data: sets[sets.length - 1] })
  return render(<DynamicAssessmentPanel assessmentId="12" language={language} evidence={[]} />)
}

beforeEach(() => {
  vi.clearAllMocks()
})

afterEach(() => {
  vi.useRealTimers()
})

describe('the draft\'s model', () => {
  it('says which model drafted the questions, and marks a fallback model', async () => {
    renderPanel([draftSet({ ai_provenance: FALLBACK_PROVENANCE })])
    expect(await screen.findByText('Made by fallback model gemini-3.1-pro-preview (step 2 of 3); the first model gemini-3.6-flash was busy.')).toBeInTheDocument()
  })

  it('draws no note for a set made before the provenance was kept', async () => {
    renderPanel([draftSet()])
    await screen.findByRole('button', { name: new RegExp(EN.approveAll) })
    expect(document.querySelector('[data-ai-provenance]')).toBeNull()
  })

  it('a question regenerated by another model names that model and marks it; the draft\'s questions carry no note of their own', async () => {
    const draft = { ...PRIMARY_PROVENANCE, call_id: 'call-draft' }
    const regenerated = { ...FALLBACK_PROVENANCE, call_id: 'call-item' }
    const questions = items(25, 'pending_review').map((item, index) => ({ ...item, ai_provenance: index === 3 ? regenerated : draft }))
    renderPanel([draftSet({ ai_provenance: draft, active_items: questions })])

    expect(await screen.findByText('Made by gemini-3.6-flash')).toBeInTheDocument()
    const own = document.querySelectorAll('[data-item-provenance]')
    expect(own).toHaveLength(1)
    expect(own[0]).toHaveAttribute('data-item-provenance', '103')
    expect(own[0]).toHaveTextContent('Made by fallback model gemini-3.1-pro-preview (step 2 of 3); the first model gemini-3.6-flash was busy.')
  })
})

describe('a draft run waiting to retry', () => {
  it('says when it tries next, holds Generate but not the set, and Retry now calls the server\'s own route for that run', async () => {
    aiApi.retryAiGenerationNow.mockResolvedValue({ data: { status: 'queued' } })
    const waiting = waitingRun({ kind: 'entry_quiz_draft', subject_id: 7 })
    renderPanel([draftSet({ generation: waiting }), draftSet({ generation: { status: 'queued' } })])

    const notice = await screen.findByRole('status', { name: 'Waiting to retry' })
    expect(notice).toHaveTextContent(/Next try: .+\. This is try 2 of 11\./)
    // The object the server sends, keyed by model, is named too (fix review).
    expect(notice).toHaveTextContent('Models tried: gemini-3.6-flash (Busy, status 503) and gemini-3.1-pro-preview (Did not answer in time).')
    expect(screen.getByText(AI_COPY.en.run.byHandStops)).toBeInTheDocument()
    // A new generation is refused while one waits; the set's own work goes on by hand.
    expect(screen.getByRole('button', { name: new RegExp(EN.regenerateAll) })).toBeDisabled()
    expect(screen.getByRole('button', { name: new RegExp(EN.send) })).toBeEnabled()
    expect(screen.queryByText(EN.generationRunning)).not.toBeInTheDocument()

    fireEvent.click(screen.getByRole('button', { name: 'Retry now' }))
    await waitFor(() => expect(aiApi.retryAiGenerationNow).toHaveBeenCalledWith(waiting))
    expect(mocks.generateDynamicAssessmentDraft).not.toHaveBeenCalled()
    expect(await screen.findByText(EN.generationQueued)).toBeInTheDocument()
  })

  it('sends the set by hand while a generation waits (the server then closes the waiting run)', async () => {
    mocks.sendDynamicAssessment.mockResolvedValue({ data: {} })
    renderPanel([draftSet({ generation: waitingRun() }), draftSet({ status: 'issued', generation: { ...waitingRun(), status: 'failed', error: { code: 'superseded_by_manual_work', class: 'superseded', messages: ['Staff continued by hand.'] } } })])
    fireEvent.click(await screen.findByRole('button', { name: new RegExp(EN.send) }))
    await waitFor(() => expect(mocks.sendDynamicAssessment).toHaveBeenCalledWith(7))
  })

  it('offers no Retry now for a run that does not name itself', async () => {
    renderPanel([draftSet({ generation: waitingRun({ kind: undefined, subject_id: undefined }) })])
    await screen.findByRole('status', { name: 'Waiting to retry' })
    expect(screen.queryByRole('button', { name: 'Retry now' })).not.toBeInTheDocument()
  })

  it('reads the set again every half minute, not every few seconds', async () => {
    vi.useFakeTimers({ shouldAdvanceTime: true })
    renderPanel([draftSet({ generation: waitingRun() })])
    await screen.findByRole('status', { name: 'Waiting to retry' })
    const reads = mocks.fetchDynamicAssessment.mock.calls.length
    await act(async () => { await vi.advanceTimersByTimeAsync(GENERATION_POLL_MS * 2) })
    expect(mocks.fetchDynamicAssessment.mock.calls.length).toBe(reads)
    await act(async () => { await vi.advanceTimersByTimeAsync(AI_RUN_WAITING_POLL_MS) })
    expect(mocks.fetchDynamicAssessment.mock.calls.length).toBeGreaterThan(reads)
  })

  it('says a run that stopped because the AI service stayed busy did so, in Arabic too', async () => {
    renderPanel([draftSet({ generation: { status: 'failed', error_code: 'ai_unavailable_window_exhausted', error_class: 'busy', error: { code: 'ai_unavailable_window_exhausted', messages: ['Gave up after 6 hours.'] } } })], 'ar')
    const alert = await screen.findByRole('alert')
    expect(alert).toHaveTextContent(COPY.ar.generationFailed)
    expect(alert).toHaveTextContent(AI_COPY.ar.errors.windowExhausted)
    expect(alert).not.toHaveTextContent('Gave up after 6 hours.')
  })
})

describe('the final evaluation on the queue', () => {
  it('says it is queued and holds the button', async () => {
    renderPanel([answeredSet({ final_evaluation_generation: { status: 'queued' } })])
    expect(await screen.findByText(AI_COPY.en.run.queued)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: EN.finalEvaluate })).toBeDisabled()
  })

  it('offers Retry now while it waits to retry, through the server\'s own route', async () => {
    aiApi.retryAiGenerationNow.mockResolvedValue({ data: { status: 'queued' } })
    const waiting = waitingRun({ kind: 'final_evaluation', subject_id: 7 })
    renderPanel([answeredSet({ final_evaluation_generation: waiting }), answeredSet({ final_evaluation_generation: { status: 'queued' } })])
    fireEvent.click(await screen.findByRole('button', { name: 'Retry now' }))
    await waitFor(() => expect(aiApi.retryAiGenerationNow).toHaveBeenCalledWith(waiting))
    expect(mocks.finalEvaluateDynamicAssessment).not.toHaveBeenCalled()
  })

  it('asks for it with the plain request, and says which model made it', async () => {
    mocks.finalEvaluateDynamicAssessment.mockResolvedValue({ data: {} })
    const evaluated = answeredSet({ final_evaluation: { model: 'gemini-3.1-pro-preview', ai_provenance: FALLBACK_PROVENANCE, advisory: { disclaimer: 'Advisory only.', evaluation_summary: 'Strong logistics practice.' } } })
    renderPanel([answeredSet(), evaluated])
    fireEvent.click(await screen.findByRole('button', { name: EN.finalEvaluate }))
    await waitFor(() => expect(mocks.finalEvaluateDynamicAssessment).toHaveBeenCalledWith(7))
    expect(await screen.findByText('Made by fallback model gemini-3.1-pro-preview (step 2 of 3); the first model gemini-3.6-flash was busy.')).toBeInTheDocument()
  })

  it('says why a queued evaluation failed', async () => {
    renderPanel([answeredSet({ final_evaluation_generation: { status: 'failed', error_code: 'provider_timeout' } })])
    expect(await screen.findByText(AI_COPY.en.errors.timeout)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: EN.finalEvaluate })).toBeEnabled()
  })
})
